interface RawBhxProduct {
  id: number;
  name: string;
  fullName: string;
  url: string;
  avatar: string;
  unit: string;
  canonical: string;
  brandName?: string;
  price?: number;
  cateId: number;
  cateUrl: string;
  cateName: string;
  groupLabel: string;
}

const rawList: RawBhxProduct[] = [];
const seenIds = new Set<number>();

function addProduct(p: RawBhxProduct) {
  if (seenIds.has(p.id)) return;
  seenIds.add(p.id);
  rawList.push(p);
}

