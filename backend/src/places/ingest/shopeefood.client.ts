/**
 * ShopeeFood (shopeefood.vn) internal web API client.
 *
 * ⚠️ ShopeeFood has NO public API. These endpoints were verified (Oct 2026) via
 * browser DevTools on shopeefood.vn and may change or be blocked at any time.
 * Crawling likely violates ShopeeFood ToS: run manually by an admin only, keep
 * rate limit ~1 req/s, store `sourceUrl` + `provider` for attribution, and keep
 * crawled places `isVerified=false` until reviewed.
 *
 * Verified endpoints (base https://gappapi.deliverynow.vn/api):
 *  - POST delivery/search_global
 *      body { category_group: 1, city_id, delivery_only: true, keyword, sort_type, foody_services: [1], full_restaurant_ids: true }
 *      -> reply.search_result[] { restaurant_ids[], restaurants[{ restaurant_id, dish_ids }] }
 *  - POST delivery/get_infos   body { restaurant_ids: number[] } (batch of ~25)
 *      -> reply.delivery_infos[] { restaurant_id, delivery_id, name, address, url,
 *           rating{avg,total_review}, position{latitude,longitude}, price_range,
 *           operating{open_time,close_time}, categories[], cuisines[], photos[] }
 *  - GET  dish/get_delivery_dishes?id_type=2&request_id=<delivery_id>
 *      -> reply.menu_infos[] { dish_type_name, dishes[{ name, price{value} }] }
 *
 * Required headers: x-foody-client-id, x-foody-client-type: 1, x-foody-app-type: 1004,
 * x-foody-client-version, x-foody-api-version: 1, x-foody-client-language: vi.
 * The web client additionally sends anti-bot signature headers (e.g. `x-sap-ri`,
 * `x-sap-sec`) generated by obfuscated JS; plain server requests get HTTP 403.
 * To crawl, copy those headers + cookie from a logged browser session into
 * env `SHOPEEFOOD_EXTRA_HEADERS` (JSON object) — they expire, so refresh as needed.
 * When blocked, use the OSM source instead.
 */
import {
  everyDay,
  fetchJsonWithRetry,
  HttpError,
  type PlaceInput,
  type PlaceMenuItem,
  RateLimiter,
  toHHmm,
} from './place-input';

const BASE = 'https://gappapi.deliverynow.vn/api';

export const SHOPEEFOOD_CITY_IDS: Record<string, number> = {
  hcm: 217,
  'ho-chi-minh': 217,
  hn: 218,
  'ha-noi': 218,
  dn: 219,
  'da-nang': 219,
};

/** sort_type values used by the web UI */
export const SHOPEEFOOD_SORT = { relevance: 8, nearest: 3, rating: 36, bestSeller: 35, fastest: 37 };

export interface ShopeeFoodClientOptions {
  minIntervalMs?: number;
  extraHeaders?: Record<string, string>;
  clientVersion?: string;
}

export class ShopeeFoodBlockedError extends Error {}

export class ShopeeFoodClient {
  private readonly limiter: RateLimiter;
  private readonly headers: Record<string, string>;

  constructor(opts: ShopeeFoodClientOptions = {}) {
    this.limiter = new RateLimiter(opts.minIntervalMs ?? 1100);
    this.headers = {
      accept: 'application/json, text/plain, */*',
      'content-type': 'application/json;charset=UTF-8',
      origin: 'https://shopeefood.vn',
      referer: 'https://shopeefood.vn/',
      'user-agent':
        'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/129.0 Safari/537.36',
      'x-foody-client-id': '',
      'x-foody-client-type': '1',
      'x-foody-app-type': '1004',
      'x-foody-client-version': opts.clientVersion ?? '3.0.0',
      'x-foody-api-version': '1',
      'x-foody-client-language': 'vi',
      ...(opts.extraHeaders ?? {}),
    };
  }

  static fromEnv(): ShopeeFoodClient {
    let extraHeaders: Record<string, string> = {};
    const raw = process.env.SHOPEEFOOD_EXTRA_HEADERS;
    if (raw) {
      try {
        extraHeaders = JSON.parse(raw);
      } catch {
        throw new Error('SHOPEEFOOD_EXTRA_HEADERS must be a JSON object');
      }
    }
    return new ShopeeFoodClient({ extraHeaders });
  }

  private async call<T>(path: string, init: RequestInit): Promise<T> {
    try {
      const json = await fetchJsonWithRetry<any>(`${BASE}/${path}`, { ...init, headers: this.headers }, {
        limiter: this.limiter,
      });
      if (json?.result && json.result !== 'success') {
        throw new Error(`ShopeeFood ${path} result=${json.result}`);
      }
      return json?.reply as T;
    } catch (e) {
      if (e instanceof HttpError && (e.status === 403 || e.status === 401)) {
        throw new ShopeeFoodBlockedError(
          `ShopeeFood blocked request (${e.status}). Anti-bot headers are required — set SHOPEEFOOD_EXTRA_HEADERS or use --source osm.`,
        );
      }
      throw e;
    }
  }

  /** Returns restaurant ids for a keyword in a city (all foody services merged, de-duplicated). */
  async searchRestaurantIds(keyword: string, cityId: number, sortType = SHOPEEFOOD_SORT.relevance) {
    const reply = await this.call<{ search_result?: { restaurant_ids?: number[] }[] }>(
      'delivery/search_global',
      {
        method: 'POST',
        body: JSON.stringify({
          category_group: 1,
          city_id: cityId,
          delivery_only: true,
          keyword,
          sort_type: sortType,
          foody_services: [1],
          full_restaurant_ids: true,
        }),
      },
    );
    const ids = new Set<number>();
    for (const group of reply?.search_result ?? []) {
      for (const id of group.restaurant_ids ?? []) ids.add(id);
    }
    return [...ids];
  }

  async getInfos(restaurantIds: number[]): Promise<any[]> {
    const out: any[] = [];
    for (let i = 0; i < restaurantIds.length; i += 25) {
      const reply = await this.call<{ delivery_infos?: any[] }>('delivery/get_infos', {
        method: 'POST',
        body: JSON.stringify({ restaurant_ids: restaurantIds.slice(i, i + 25) }),
      });
      out.push(...(reply?.delivery_infos ?? []));
    }
    return out;
  }

  async getMenu(deliveryId: number): Promise<PlaceMenuItem[]> {
    const reply = await this.call<{ menu_infos?: any[] }>(
      `dish/get_delivery_dishes?id_type=2&request_id=${deliveryId}`,
      { method: 'GET' },
    );
    return parseShopeeFoodMenu(reply);
  }
}

export function parseShopeeFoodMenu(reply: any): PlaceMenuItem[] {
  const items: PlaceMenuItem[] = [];
  for (const group of reply?.menu_infos ?? []) {
    for (const d of group?.dishes ?? []) {
      if (!d?.name) continue;
      const price = Number(d?.discount_price?.value ?? d?.price?.value);
      items.push({ name: String(d.name).trim(), priceVnd: Number.isFinite(price) && price > 0 ? price : null });
    }
  }
  return items;
}

/** Map a `delivery_infos[]` entry to the normalized PlaceInput. */
export function mapShopeeFoodInfo(info: any, menu: PlaceMenuItem[] = []): PlaceInput | null {
  const id = info?.restaurant_id ?? info?.id;
  if (!id || !info?.name) return null;
  const lat = Number(info?.position?.latitude);
  const lng = Number(info?.position?.longitude);
  const avg = Number(info?.rating?.avg);
  const total = Number(info?.rating?.total_review);

  const open = toHHmm(info?.operating?.open_time);
  const close = toHHmm(info?.operating?.close_time);
  // "00:00:01 - 23:59:59" means open all day -> same open/close = 24h in computeOpenStatus
  const allDay = open === '00:00' && close === '23:59';

  const menuPrices = menu.map((m) => m.priceVnd).filter((p): p is number => !!p && p > 0);
  const pr = info?.price_range ?? {};
  const priceMin = Number(pr.min_price) || (menuPrices.length ? Math.min(...menuPrices) : null);
  const priceMax = Number(pr.max_price) || (menuPrices.length ? Math.max(...menuPrices) : null);

  const photos: any[] = Array.isArray(info?.photos) ? info.photos : [];
  const thumb = photos.length ? photos[photos.length - 1]?.value ?? photos[0]?.value : null;

  return {
    provider: 'SHOPEEFOOD',
    providerPlaceId: String(id),
    name: String(info.name).slice(0, 200),
    addressShort: info?.address ? String(info.address).slice(0, 300) : null,
    lat: Number.isFinite(lat) && lat !== 0 ? lat : null,
    lng: Number.isFinite(lng) && lng !== 0 ? lng : null,
    thumbnailUrl: thumb ?? null,
    ratingAvg: Number.isFinite(avg) && avg > 0 ? Math.min(5, avg) : null,
    ratingCount: Number.isFinite(total) && total > 0 ? total : null,
    priceMin: priceMin || null,
    priceMax: priceMax || null,
    openingHours: open && close ? (allDay ? everyDay('00:00', '00:00') : everyDay(open, close)) : null,
    categoryTags: [...(info?.categories ?? []), ...(info?.cuisines ?? [])].map(String).filter(Boolean),
    sourceUrl: info?.url ?? (info?.restaurant_url ? `https://shopeefood.vn/${info.location_url ?? 'ho-chi-minh'}/${info.restaurant_url}` : null),
    menu,
    raw: {
      restaurantId: info?.restaurant_id ?? null,
      deliveryId: info?.delivery_id ?? null,
      cityId: info?.city_id ?? null,
      categories: info?.categories ?? [],
      cuisines: info?.cuisines ?? [],
      menu: menu.slice(0, 300),
    },
  };
}
